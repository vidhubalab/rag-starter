// Function to generate realistic candle data for interactive charts
export function generateCandles(basePrice: number, count: number = 30, volatility: number = 0.015): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let current = basePrice * 0.95;
  const now = Date.now();
  const step = 24 * 60 * 60 * 1000; // 1 day

  for (let i = count; i >= 0; i--) {
    const time = new Date(now - i * step).toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    const change = (Math.random() - 0.48) * volatility * current;
    const open = Number(current.toFixed(2));
    const close = Number((current + change).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * volatility * current * 0.8).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * volatility * current * 0.8).toFixed(2));
    const volume = Math.floor(Math.random() * 15000000) + 2000000;

    candles.push({ time, open, high, low, close, volume });
    current = close;
  }
  return candles;
}

